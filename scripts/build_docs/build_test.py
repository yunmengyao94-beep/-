bullets(
    doc,
    [
        "现象：借用人完成归还后，物品仍显示「已被借出」，再也无法被借用。",
        "定位：orders.js 只在下单时把 item.status 置 1，完成订单时没有复位。",
        "修复：在确认归还分支将 item.status 复位为 0；同时补订单状态筛选边界（state 允许 0–5）。",
        "回归：借用→归还→再次借用成功；提交 e8fe5b4 / 05a3e05。",
    ],
)

h3(doc, "BUG-02  逾期没有任何处理")
bullets(
    doc,
    [
        "现象：超过约定时间未归还，订单状态不变、信用分不扣、出借人无感知。",
        "定位：原设计缺少定时任务，也没有读取时的惰性判定。",
        "修复：新增 applyOverduePenalties()，在读取个人中心与订单列表时执行；置 state=4，"
        "按已满 24 小时每天扣 5 分，用 penalty_days 保证幂等，并给双方发通知。",
        "回归：due_at 设为 2 天前，首次读取扣 10 分、重复读取不再扣；提交 d2f676f。",
    ],
)

h3(doc, "BUG-03  出借人无权确认归还")
bullets(
    doc,
    [
        "现象：借用人点「发起归还」即直接完成订单并解冻，出借人无法确认物品状态。",
        "定位：状态机只有 request_return 一个动作，缺少出借人角色校验。",
        "修复：拆为 request_return（1/4→5）与 confirm_return（5→2），后者仅出借人可调用；"
        "物品释放与解冻移到确认归还时执行。",
        "回归：借用人调 confirm_return 返回 403；出借人确认后冻结归零、物品可借；提交 d2f676f。",
    ],
)

h3(doc, "BUG-04  认证奖励可被直接刷取")
